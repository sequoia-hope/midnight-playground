/// Boost the turbo would make at this rpm and throttle, once spooled
/// (`boostTarget`).
pub fn boost_target(p: &Params, rpm: f64, thr: f64) -> f64 {
    if p.turbo == 0.0 {
        return 0.0;
    }
    thr * ((rpm - 0.3 * p.redline) / (0.35 * p.redline)).clamp(0.0, 1.0)
}
